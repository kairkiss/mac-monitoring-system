// Current language
let _lang = localStorage.getItem('language') || '';

function detectLanguage() {
  if (_lang && I18N[_lang]) return _lang;
  const nav = navigator.language || navigator.userLanguage || 'en';
  if (nav.startsWith('zh')) return 'zh';
  return 'en';
}

function setLanguage(lang) {
  if (!I18N[lang]) return;
  _lang = lang;
  localStorage.setItem('language', lang);
  applyI18N();
}

function t(key) {
  const lang = detectLanguage();
  const val = I18N[lang] && I18N[lang][key];
  if (val !== undefined) return val;
  // Fallback to English
  return I18N.en[key] || key;
}

function applyI18N() {
  // Apply data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = t(key);
    if (el.tagName === 'INPUT' && el.type !== 'submit') {
      el.placeholder = text;
    } else {
      el.textContent = text;
    }
  });
  // Apply data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  // Update page title if data-i18n-title on <title>
  const titleEl = document.querySelector('title[data-i18n]');
  if (titleEl) document.title = t(titleEl.getAttribute('data-i18n'));
}

// Auto-apply on DOMContentLoaded (runs before page-specific scripts)
document.addEventListener('DOMContentLoaded', () => {
  applyI18N();
});
